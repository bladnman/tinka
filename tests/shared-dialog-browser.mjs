// Follow the real New Board entry points and modal pointer behavior.
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,readFile,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {main} from '../cli.mjs';
import {loadConfig} from '../lib/config.mjs';
import {applyOperation} from '../lib/workspace.mjs';

const {chromium} = await import(process.env.PLAYWRIGHT_MODULE
  ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const fixture = await mkdtemp(path.join(os.tmpdir(),'tinka-shared-dialog-'));
const configFile = path.join(fixture,'config.json'), evidence = process.env.TINKA_EVIDENCE_DIR;
let browser, started;
try {
  await main(['init','--config',configFile,'--boards',path.join(fixture,'boards'),'--label','Exploration studio']);
  await main(['workspace','init','--config',configFile,'--apply']);
  const config = await loadConfig(configFile);
  const {result:{boardId}} = await applyOperation(config,{type:'createBoard',title:'Reading studies'});
  await applyOperation(config,{type:'createItem',boardId,item:{title:'Opening notes'}});
  await main(['start','--config',configFile]);
  started = true;
  const {port} = JSON.parse(await readFile(configFile,'utf8')), base = `http://127.0.0.1:${port}`;
  browser = await chromium.launch({headless:true,...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{})});
  const page = await browser.newPage({viewport:{width:1440,height:960},reducedMotion:'reduce'});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const post = request => request.method() === 'POST' && request.url() === `${base}/api/operations`;
  const writes = [];
  page.on('request', request => { if (post(request)) writes.push(request.postDataJSON()); });
  const dialog = page.getByRole('dialog',{name:'New board'}), name = dialog.getByLabel('Board name');
  const inside = async element => {
    const box = await element.boundingBox();
    return {x:box.x + box.width / 2,y:box.y + box.height / 2};
  };
  const detached = target => target.waitFor({state:'detached'});
  const focused = target => target.evaluate(element => element === document.activeElement);
  const shot = async file => { if (evidence) { await mkdir(evidence,{recursive:true}); await page.screenshot({path:path.join(evidence,file)}); } };

  let resumeHome, graphAsked;
  const homeGate = new Promise(resolve => resumeHome = resolve), graphRequest = new Promise(resolve => graphAsked = resolve);
  await page.route('**/api/workspace?view=home',async route => { graphAsked(); await homeGate; await route.continue(); });
  await page.goto(base,{waitUntil:'commit'});
  await graphRequest;
  const masthead = page.getByRole('button',{name:'New board',exact:true});
  await masthead.click();
  assert.equal(await page.locator('#new-dialog[open]').count(),0,'Early New Board waits for graph Home.');
  resumeHome();
  await dialog.waitFor();
  await page.unroute('**/api/workspace?view=home');
  await page.keyboard.press('Escape'); await detached(dialog);
  assert.ok(await focused(masthead));
  await page.locator('[data-home-item]').first().waitFor();
  const home = page.locator('.new-board.empty-card');
  await home.click();
  assert.ok(await focused(name));
  const homeBox = await dialog.boundingBox();
  assert.ok(homeBox.width <= 360 && homeBox.height < 220);
  await page.mouse.click(homeBox.x + homeBox.width / 2,homeBox.y + 5);
  assert.ok(await dialog.isVisible(),'Dialog padding is inside the dialog.');
  await name.fill('Local reading lab');
  await name.click();
  const p = await inside(name);
  await page.mouse.move(p.x,p.y); await page.mouse.down();
  await page.mouse.move(7,8,{steps:6}); await page.mouse.up();
  assert.ok(await dialog.isVisible(),'A drag from a field onto the backdrop keeps the form open.');
  await page.mouse.click(7,8); await detached(dialog);
  assert.ok(await focused(home));
  assert.equal(writes.length,0);
  await home.press('Enter');
  assert.equal(await name.inputValue(),'Local reading lab');
  await shot('new-board-home-1440.png');
  await page.keyboard.press('Escape'); await detached(dialog);
  assert.ok(await focused(home));
  await home.click(); await name.press('Enter'); await detached(dialog);
  await page.getByRole('heading',{name:'Local reading lab',exact:true}).waitFor();
  assert.deepEqual(writes.map(x=>x.type),['createBoard']);
  assert.equal(writes[0].parentBoardId,undefined);

  await page.setViewportSize({width:390,height:690});
  await page.goto(`${base}/boards/${boardId}/`);
  const add = page.locator('#workspace-add');
  const open = async item => { await add.click(); await page.getByRole('menuitem',{name:item,exact:true}).click(); };
  await open('Item…');
  const idea = page.getByRole('dialog',{name:'Add an idea'});
  const footer = idea.locator('.workspace-dialog-actions');
  const hintBox = await footer.locator('.workspace-submit-hint').boundingBox();
  const actionBox = await footer.getByRole('button',{name:'Add idea'}).boundingBox();
  assert.ok(actionBox.x - (hintBox.x + hintBox.width) >= 16,'The shared footer separates the hint and action.');
  await page.mouse.click(7,8); await detached(idea);

  await open('Tinka / Board…');
  assert.ok(await focused(name));
  const compact = await dialog.boundingBox();
  assert.ok(compact.x >= 10 && compact.width <= 360 && compact.height < 220);
  await name.fill('Child reading lab');
  await shot('new-board-canvas-390.png');
  await dialog.getByRole('button',{name:'Close dialog'}).click(); await detached(dialog);
  assert.ok(await focused(add));
  await open('Tinka / Board…');
  assert.equal(await name.inputValue(),'Child reading lab');

  let release, arrived;
  const paused = new Promise(resolve => release = resolve), atServer = new Promise(resolve => arrived = resolve);
  await page.route('**/api/operations', async route => {
    if (route.request().postDataJSON()?.type !== 'createBoard') return route.continue();
    arrived();
    await paused;
    await route.fulfill({status:503,json:{error:'Could not create the board. Try again.'}});
  });
  await name.press('Enter'); await atServer;
  await page.mouse.click(7,8);
  assert.ok(await dialog.isVisible(),'A pending create keeps the form open.');
  release();
  await dialog.getByRole('alert').getByText('Could not create the board. Try again.').waitFor();
  assert.equal(await name.inputValue(),'Child reading lab');
  await page.unroute('**/api/operations');
  await name.press('Control+Enter'); await detached(dialog);
  await page.getByRole('heading',{name:'Child reading lab',exact:true}).waitFor();
  assert.equal(writes.at(-1).operationId,writes.at(-2).operationId);
  assert.equal(writes.at(-1).parentBoardId,boardId);
  await open('Tinka / Board…');
  assert.equal(await name.inputValue(),'','Reopen after a successful creation starts a fresh name.');
  await page.keyboard.press('Escape'); await detached(dialog);
  const inspector = page.locator('#board-info-toggle');
  await inspector.click();
  await page.locator('#board-info [data-appearance-set="dark"]').click();
  await inspector.click();
  await page.waitForFunction(() => document.documentElement.dataset.appearance === 'dark');
  await open('Tinka / Board…');
  await name.fill('Evening studies');
  await shot('new-board-canvas-dark-390.png');
  assert.deepEqual(errors,[]);
  console.log('Shared dialogs passed: actual outside-click vs drag, focus, narrow footer, Home and Canvas creation, and one retry with its draft.');
} finally {
  await browser?.close();
  if (started) await main(['stop','--config',configFile]);
  await rm(fixture,{recursive:true,force:true});
}
