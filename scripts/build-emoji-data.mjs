import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

// Maintainer command: node scripts/build-emoji-data.mjs [--check]
// This is the only step that requires a connection to the upstream sources.
const version = '18.0';
const baseline = 15.1; // Node 22.0.0 ships Unicode 15.1.
const cldrRevision = '96e54b273d2da4ec6fbad350ba19ff23fa24a588'; // release-49
const cldrBase = `https://raw.githubusercontent.com/unicode-org/cldr/${cldrRevision}`;
const sources = [
  [`https://www.unicode.org/Public/${version}.0/emoji/emoji-test.txt`, '8f3735cda1f92a779d78af67cf86066bb1f07143dc22f2ac29394d9bc57ab21a'],
  [`${cldrBase}/common/annotations/en.xml`, '14d0e9bb5003c085250df4ac7bd7ba1e26d92e74174d7a3a2f42dc16e07fb155'],
  [`${cldrBase}/common/annotationsDerived/en.xml`, 'a4a6c1a4c341d94179cb116623c5f44c47400a5bc55da483423ef7430ecf622e'],
  [`${cldrBase}/LICENSE`, '65eb33419e22a297550a811b5b535f5e532f9a7e0114b516c0ea18afd53c3804'],
];

async function fetchPinned([url, digest]) {
  const response = await fetch(url, { signal: AbortSignal.timeout(20_000) });
  assert.ok(response.ok, `${url}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  assert.equal(createHash('sha256').update(bytes).digest('hex'), digest, `Source changed: ${url}`);
  return bytes.toString('utf8');
}

function annotationsFrom(documents) {
  const entities = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" };
  const decode = (value) => value.replace(/&([^;]+);/g, (_, key) => {
    assert.ok(Object.hasOwn(entities, key), `Unhandled CLDR XML entity: &${key};`);
    return entities[key];
  });
  const byEmoji = new Map();
  // Both pinned CLDR files use one plain-text annotation per line.
  for (const xml of documents) for (const line of xml.split('\n')) {
    if (!line.trimStart().startsWith('<annotation ')) continue;
    const match = line.match(/<annotation cp="([^"]*)"( type="tts")?>([^<]+)<\/annotation>/);
    assert.ok(match, `Unexpected CLDR annotation: ${line.trim()}`);
    const [, key, shortName, value] = match;
    const emoji = decode(key);
    const terms = byEmoji.get(emoji) ?? new Set();
    for (const term of decode(value).split(/\s*\|\s*/)) {
      if (term && term !== '↑↑↑') terms.add(term);
    }
    // A tts row can provide a useful synonym when it differs from emoji-test.txt.
    if (shortName) assert.ok(!value.includes('|'), `Unexpected CLDR short name: ${line.trim()}`);
    byEmoji.set(emoji, terms);
  }
  return byEmoji;
}

const args = process.argv.slice(2);
const check = args[0] === '--check';
assert.ok(args.length === 0 || (check && args.length === 1), 'Usage: node scripts/build-emoji-data.mjs [--check]');

const [emojiTest, regularAnnotations, derivedAnnotations, cldrLicense] = await Promise.all(sources.map(fetchPinned));
assert.ok(emojiTest.split('\n').includes(`# Version: ${version}`));
const annotations = annotationsFrom([regularAnnotations, derivedAnnotations]);
const groups = [];
const entries = [];
const additions = [];
let components = 0;
for (const line of emojiTest.split('\n')) {
  if (line.startsWith('# group: ')) groups.push(line.slice('# group: '.length));
  if (!line || line.startsWith('#')) continue;
  const match = line.match(/^([0-9A-F ]+)\s*;\s*([\w-]+)\s*#\s*(\S+) E(\d+\.\d+) (.+)$/);
  assert.ok(match, `Unexpected Unicode emoji row: ${line}`);
  const [, points, status, display, introduced, name] = match;
  if (status !== 'fully-qualified' && status !== 'component') continue;
  const emoji = String.fromCodePoint(...points.trim().split(/\s+/).map((point) => Number.parseInt(point, 16)));
  assert.equal(emoji, display, `Code point and display columns differ for ${name}`);
  const groupIndex = groups.length - 1;
  assert.ok(groupIndex >= 0);
  if (status === 'component') {
    assert.equal(groups[groupIndex], 'Component');
    components += 1;
  }
  // CLDR drops variation selectors from keys; retain them in the saved emoji.
  const terms = annotations.get(emoji.replaceAll('\uFE0F', ''));
  assert.ok(terms?.size, `Missing CLDR annotations for ${name}`);
  const keywords = [...terms].filter((term) => term.toLowerCase() !== name.toLowerCase()).join('|');
  entries.push([emoji, name, keywords, groupIndex]);
  if (Number(introduced) > baseline) additions.push(emoji);
}
assert.equal(components, 9);
assert.equal(entries.length - components, 3963);
assert.equal(new Set(entries.map(([emoji]) => emoji)).size, entries.length, 'Duplicate emoji');
assert.equal(additions.length, 190);

const header = '// Generated by scripts/build-emoji-data.mjs. Unicode data: see UNICODE-EMOJI-LICENSE.txt.\n';
const catalogue = `${header}`
  + `export const emojiVersion = ${JSON.stringify(version)};\n`
  + `export const emojiGroups = ${JSON.stringify(groups)};\n`
  + '// [emoji, English name, English keywords (pipe-separated), group index]\n'
  + `export const emojiEntries = [\n${entries.map((entry) => `  ${JSON.stringify(entry)},`).join('\n')}\n];\n`;
const latest = `${header}`
  + `// Emoji added after ${baseline}, for runtimes whose Unicode tables predate this repertoire.\n`
  + `export const newEmoji = new Set(${JSON.stringify(additions)});\n`;
const attribution = 'Tinka uses Unicode Emoji 18.0 test data and CLDR release 49 English annotations.\n'
  + 'Emoji test data: © 2026 Unicode®, Inc. Unicode and the Unicode Logo are\n'
  + 'registered trademarks of Unicode, Inc. in the U.S. and other countries.\n'
  + 'CLDR data: Copyright © 1991-2026 Unicode, Inc.\n'
  + 'Terms of use: https://www.unicode.org/copyright.html\n'
  + 'SPDX-License-Identifier: Unicode-3.0\n\n'
  + `Upstream sources and SHA-256 digests:\n${sources.map(([url, digest]) => `${url}\n  ${digest}`).join('\n')}\n\n`
  + 'The upstream CLDR notice follows. The annotation data and emoji test data use Unicode License v3.\n\n'
  + cldrLicense;

for (const [name, content] of [
  ['emoji-repertoire.js', catalogue],
  ['emoji-repertoire-additions.js', latest],
  ['UNICODE-EMOJI-LICENSE.txt', attribution],
]) {
  const file = new URL(`../public/${name}`, import.meta.url);
  if (check) assert.ok((await readFile(file)).equals(Buffer.from(content)), `${name} is out of date`);
  else await writeFile(file, content);
}

console.log(`Emoji ${version}: ${entries.length} total, ${components} components, ${additions.length} additions (${check ? 'verified' : 'generated'})`);
